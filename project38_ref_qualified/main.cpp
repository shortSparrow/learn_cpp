#include <iostream>
#include <string>
#include <utility> // Для std::move

/**
 * Кожен вираз у C++ є або lvalue (значення, яке має певну ідентичність і може бути розміщене з лівого боку оператора присвоєння),
 * або rvalue (тимчасове значення, яке зазвичай використовується праворуч).
 *
 * lvalue (L-значення): Вирази, які позначають об'єкт, що має ідентичність і може існувати довгий час (наприклад, змінна x).
 * rvalue (R-значення): Тимчасові вирази, які не мають ідентичності (наприклад, літерал 5 або результат a + b).
 *
 * Якщо функція викликається на lvalue об'єкті (наприклад, Employee e; e.getName();), об'єкт e продовжить
 * існувати після повернення функції, і посилання є безпечним.
 *
 * Якщо функція викликається на rvalue об'єкті (наприклад, createEmployee("Bob").getName();), rvalue об'єкт,
 * створений функцією createEmployee, знищується в кінці повного виразу. Повернене посилання стає висячим
 * (dangling reference), і спроба його використати призводить до невизначеної поведінки.
 *
 *
 * Коли ми робимо перевантажуємо метод за допомогою кваліфікатора & то ми вказуємо що має повернутися для lvalue
 * Коли ми робимо перевантажуємо метод за допомогою кваліфікатора && то ми вказуємо що має повернутися для rvalue
 *
 * Тож якщо ви визначили лише lvalue, то коли ми спробуємо взяти це значення як rvalue то компілятор видасть помилку.
 * Або ми можемо перевизначити обидва і & і && і бути впевненим що при lvalue все буде працювати добре з reference, а
 * коли буде rvalue то reference перетвориться на значення
 *
 */


class Employee {
private:
    std::string m_left  { "Lvalue Data" };
    std::string m_right { "Rvalue Data" };
    std::string m_name  { "Common Data" };

public:
    // Допоміжна функція для ініціалізації
    Employee(const std::string& name) : m_name(name) {}

    // ----------------------------------------------------------------
    // 1. ТІЛЬКИ КВАЛІФІКАТОР & (Для lvalue)
    // Повертає посилання.
    std::string& getOnlyLeft() & {
        std::cout << "(Викликано getOnlyLeft() &)\n";
        return m_left;
    }

    // ----------------------------------------------------------------
    // 2. ТІЛЬКИ КВАЛІФІКАТОР && (Для rvalue)
    // Повертає за значенням (або переміщує), щоб бути безпечним.
    std::string getOnlyRight() && {
        std::cout << "(Викликано getOnlyRight() && - Переміщення)\n";
        return std::move(m_right); // Використовуємо move, оскільки об'єкт тимчасовий і буде знищено
    }

    // ----------------------------------------------------------------
    // 3. ПЕРЕВАНТАЖЕННЯ (Обидва: & та &&)
    // lvalue версія (ефективність - повертає посилання)
    const std::string& getName() const & {
        std::cout << "(Викликано getName() & - Посилання)\n";
        return m_name;
    }

    // rvalue версія (безпека/ефективність - повертає за значенням/переміщення)
    std::string getName() && {
        std::cout << "(Викликано getName() && - Переміщення)\n";
        return std::move(m_name);
    }
};

// Функція, що повертає rvalue (тимчасовий об'єкт)
Employee createEmployee(const std::string& name) {
    return Employee{ name };
}

int main() {
    Employee joe { "Joe" };

    // rvalue (тимчасовий об'єкт)
    // createEmployee("Frank") повертає rvalue

    std::cout << "======================================\n";
    std::cout << "1. ТІЛЬКИ КВАЛІФІКАТОР & (Для lvalue):\n";
    std::cout << "======================================\n";

    // ✅ Працює: lvalue викликає версію &
    std::cout << "Lvalue (joe): " << joe.getOnlyLeft() << "\n";

    /**
     * ❌ Помилка: rvalue НЕ може викликати неконстантну версію &
     * Справа в тому, що rvalue не може бути передано як неконстантне lvalue посилання.
     * Error: cannot bind rvalue to lvalue reference
     */
    std::cout << "Rvalue (createEmployee): " << createEmployee("Frank").getOnlyLeft() << "\n";


    std::cout << "======================================\n";
    std::cout << "2. ТІЛЬКИ КВАЛІФІКАТОР && (Для rvalue):\n";
    std::cout << "======================================\n";

    // ✅ Працює: rvalue викликає версію &&
    std::cout << "Rvalue (createEmployee): " << createEmployee("Frank").getOnlyRight() << "\n\n";

    /*
     * ❌ Помилка: lvalue НЕ може викликати версію &&
     * lvalue може викликати лише & або некваліфіковані функції.
     * (Error: object is not rvalue)
     */
    std::cout << "Lvalue (joe): " << joe.getOnlyRight() << "\n";





    std::cout << "======================================\n";
    std::cout << "3. ПЕРЕВАНТАЖЕННЯ (& та &&):\n";
    std::cout << "======================================\n";

    // ✅ Працює: lvalue викликає версію const & (повертає посилання)
    // Це ефективно, бо joe є іменованим об'єктом.
    std::cout << "Lvalue (joe): " << joe.getName() << "\n";

    // ✅ Працює: rvalue викликає версію && (безпечно переміщує дані)
    // Це безпечно, бо тимчасовий об'єкт буде одразу знищено.
    std::cout << "Rvalue (createEmployee): " << createEmployee("Garbo").getName() << "\n";

    return 0;
}