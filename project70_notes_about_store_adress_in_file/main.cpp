
/**
 * Запис у файл і проблема з вказівниками
 *
 * Коли у C++ ми працюємо з pointer (вказівниками), ми ЗАВЖДИ (на 100%) працюємо
 * з адресами в оперативній пам'яті (RAM). Вказівники взагалі не вміють посилатися на жорсткий диск.
 *
 * Сценарій 1: Як це працює в пам'яті
 * Створюємо звичайну змінну: int nValue = 5;
 * Нехай операційна система виділила під неї адресу 0x0012FF7C.
 * Тепер створюємо вказівник, який записує цю адресу: int* pnValue = &nValue;
 * Зараз змінна pnValue всередині себе містить числовий код адреси: 0x0012FF7C.
 *
 * Сценарій 2: Спроба зберегти це на диск
 * Ми створюємо текстовий файл і записуємо туди не значення '5', а вміст змінної pnValue
 * (тобто текст чи число "0x0012FF7C"). Файл успішно зберігся на жорсткому диску.
 *
 * Що відбувається після перезапуску комп'ютера або програми:
 * 1. Файл на диску залишився, і всередині нього досі написано "0x0012FF7C".
 * 2. Ми запускаємо програму знову. Вона зчитує з файлу цей текст "0x0012FF7C" і записує його у вказівник.
 * 3. Ми намагаємося перейти за цим вказівником в RAM, але там не буде цього значення, там буде якесь сміття.
 *
 * Висновок: Ніколи не записувати адреси пам'яті у файли. Змінні, які спочатку знаходилися за цими адресами,
 * можуть мати інші адреси.
 */