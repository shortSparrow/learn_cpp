#include <iostream>
#include <atomic>
#include <thread>
#include <vector>


/**
 * std::atomic_flag flag
 * std::atomic_flag — це найпростіший атомарний примітив у стандартній бібліотеці C++.
 * Він являє собою атомарний булевий прапорець, який може перебувати лише у двох станах:
 * встановлений (set) або скинутий (clear).
 *
 * Головні технічні особливості:
 *  - Гарантія Lock-Free: Це єдиний атомарний тип у C++, для якого стандарт гарантує повну відсутність
 *    блокувань (lock-free) на рівні апаратної архітектури. Для інших типів, як-от std::atomic<bool>
 *    або std::atomic<int>, реалізація може використовувати внутрішні м'ютекси (хоча на сучасних CPU
 *    вони зазвичай теж lock-free, стандарт цього не обіцяє).
 *
 *  - Відсутність операцій завантаження/збереження: На відміну від std::atomic<bool>, у std::atomic_flag
 *    немає методів load() або store(). Ви не можете просто "прочитати" його поточний стан, не змінивши
 *    його атомарно.
 *
 *  - Ініціалізація: Починаючи з C++20, за замовчуванням він ініціалізується у стані clear.
 *    У старіших стандартах (C++11 / C++14 / C++17) його стан за замовчуванням був невизначеним, і для
 *    ініціалізації у стані clear обов'язково використовувався макрос ATOMIC_FLAG_INIT.
 *
 * Головні методи test_and_set() та clear()
 *  bool test_and_set(std::memory_order order = std::memory_order_seq_cst) noexcept
 *  Цей метод виконує дві дії за один атомарний крок (операція типу Read-Modify-Write):
 *   - Встановлює прапорець у стан true (set).
 *   - Повертає те значення, яке прапорець мав до моменту виклику цієї функції.
 *
 *   Тобто, якщо прапорець був false, функція зробить його true і поверне false. Якщо він вже був true,
 *   вона залишить його true і поверне true.
 *
 *  void clear(std::memory_order order = std::memory_order_seq_cst) noexcept
 *  Ця операція є простим атомарним записом (Store): Скидає стан прапорця у false (clear).
 *
 * Параметр std::memory_order
 * Обидва методи приймають аргумент упорядкування пам'яті (std::memory_order).
 * За замовчуванням використовується std::memory_order_seq_cst (sequential consistency) — найсуворіша модель,
 * яка гарантує глобальний порядок операцій для всіх потоків, але є найбільш ресурсомісткою.
 *
 * Ситуація: Потік А та потік Б одночасно викликають метод test_and_set() для одного й того самого
 * об'єкта std::atomic_flag, який початково перебував у стані clear (false).
 *
 * Потік А першим зчитує початкове значення (false), фіксує його як повернене значення і перезаписує
 * прапорець на true. Потік Б, виконуючи інструкцію на такт пізніше, зчитує вже оновлене значення (true),
 * повертає його і знову записує true (фактично залишаючи стан незмінним). У результаті прапорець
 * залишається в стані true.
 *
 *
 * Найкращим прикладом практичної реалізації std::atomic_flag є Spinlock
 *
 * Для чого потрібен Spinlock?
 * Звичайний std::mutex працює через операційну систему: якщо потік намагається захопити заблокований
 * м'ютекс, ОС "присипляє" цей потік (відбувається перемикання контексту — context switch).
 * Це важка операція, яка займає відносно багато часу.
 *
 * Spinlock (циклічне блокування) потрібен тоді, коли очікується, що критична секція
 * (код, який треба захистити) виконується дуже швидко (наприклад, просто інкремент змінної
 * або додавання елемента в чергу). Замість того щоб витрачати ресурси на "засинання" та
 * "пробудження" через ОС, потік просто "крутиться" у нескінченному циклі на CPU, чекаючи,
 * поки інший потік звільнить прапорець.
 *
 *
 * Опис коду нижче
 * Уяви, що у нас є об'єкт Spinlock. Початковий стан flag за замовчуванням — false (блокування вільне).
 * Крок 1: Потік А намагається захопити вільний Spinlock
 *  1) Потік А викликає lock().
 *  2) Виконується flag.test_and_set().
 *  3) Оскільки початковий стан flag був false, функція test_and_set() робить дві речі атомарно:
 *      - Змінює стан flag на true.
 *      - Повертає попереднє значення, тобто false.
 *
 * Умова циклу while(false) не виконується. Потік А миттєво виходить із циклу while і йде виконувати критичну секцію. Блокування захоплено.
 *
 * Крок 2: Потік Б намагається захопити Spinlock, поки Потік А ще працює
 *  1) Потік Б викликає lock().
 *  2) Виконується flag.test_and_set().
 *  3) Оскільки Потік А вже встановив flag у true, функція test_and_set() потоку Б:
 *      - Залишає стан flag як true.
 *      - Повертає попереднє значення, тобто true.
 *  4) Умова циклу стає while(true). Потік Б залишається всередині циклу і знову йде на наступну ітерацію while.
 *
 * Потік Б буде циклічно виконувати test_and_set(), постійно отримувати true і залишатися в циклі. Він "крутиться" (spins),
 * навантажуючи процесорне ядро на 100%.
 *
 * Крок 3: Потік А звільняє Spinlock
 *  void unlock() {
 *      flag.clear(std::memory_order_release);
 *  }
 *  1) Потік А завершив роботу і викликає unlock().
 *  2) Метод flag.clear() просто записує у flag значення false.
 *  3) На наступній же ітерації циклу while у Потоку Б метод test_and_set() побачить, що значення стало false, поверне false,
 *  встановить прапорець знову в true для себе і вийде з циклу. Потік Б захопив блокування.
 *
 */


class Spinlock {
private:
    std::atomic_flag flag = ATOMIC_FLAG_INIT; // або просто = {} для C++20

public:
    void lock() {
        /** 
         * Потік 1 викликає .lock() і оскільки початкове значення у flag false він ставить
         * true, але повертає старе значення - false, тому ми виходимо із циклу
         * Коли Потік 2 спробує викликати .lock() до виклику Потоком 1 .unlock(), то він
         * застрягне на циклі while, бо flag.test_and_set() буде повертати true, і
         * лише після .unlock() flag.test_and_set запише знову true і поверне попереднє
         * значення - false, і тоді Потік 2 вийде із циклу і зможе виконати свої дії.
         */
        while (flag.test_and_set(std::memory_order_acquire)) {
            // spin / за бажанням тут можна викликати std::this_thread::yield()
            // або ассемблерну інструкцію PAUSE для оптимізації CPU
        }
    }

    void unlock() {
        // Атомарно скидаємо прапорець, дозволяючи іншому потоку вийти з циклу lock()
        flag.clear(std::memory_order_release);
    }
};


// Спільні дані, до яких потоки матимуть доступ
int shared_resource = 0;
Spinlock my_spinlock;

void do_heavy_work(int thread_id) {
    // 1. ЗАХОПЛЕННЯ БЛОКУВАННЯ
    my_spinlock.lock();

    // ---------------------------------------------------------------
    // КРИТИЧНА СЕКЦІЯ (Тут потік робить свою "важку роботу")
    // Сюди одночасно може зайти ЛИШЕ ОДИН потік.

    shared_resource++;
    std::cout << "Thread " << thread_id << " updated resource to " << shared_resource << "\n";

    // Імітація якоїсь роботи
    std::this_thread::sleep_for(std::chrono::milliseconds(50));
    // ---------------------------------------------------------------

    // 2. ЗВІЛЬНЕННЯ БЛОКУВАННЯ
    my_spinlock.unlock();
}

int main() {
    std::vector<std::thread> threads;

    // Запускаємо 5 потоків, які одночасно захочуть виконати do_heavy_work
    for (int i = 0; i < 5; ++i) {
        threads.emplace_back(do_heavy_work, i);
    }

    for (auto& th : threads) {
        th.join();
    }
    return 0;
}