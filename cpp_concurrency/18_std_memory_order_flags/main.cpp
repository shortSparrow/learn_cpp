#include <iostream>
#include <atomic>
#include <thread>
#include <vector>


/**
 * std::memory_order_acquire, memory_order_acq_rel, std::memory_order_release
 *
 * Ці три константи є частиною моделі пам'яті в C++ (C++ Memory Model). Вони потрібні для того,
 * щоб керувати тим, як процесор та компілятор можуть переставляти інструкції (reordering) у
 * багатопотокових програмах.
 *
 *  1) std::memory_order_release (Семантика публікації)
 *     Цей режим використовується виключно для операцій запису (store, exchange).
 *     Він діє як «одностороння стіна» для інструкцій. Він гарантує, що усі попередні записи в пам'ять
 *     (як звичайні, так і атомарні), які стоять у коді ВИЩЕ, завершаться ДО того, як відбудеться цей запис.
 *     Ніщо не може «впасти» нижче цієї лінії.
 *
 *  2) std::memory_order_acquire (Семантика отримання)
 *     Цей режим використовується виключно для операцій читання (load).
 *     Він теж працює як «одностороння стіна», але навпаки. Він гарантує, що жодні наступні операції читання
 *     чи запису, які стоять у коді НИЖЧЕ, не можуть бути виконані процесором заздалегідь (вище цього читання).
 *
 *  3) std::memory_order_acq_rel (Acquire + Release)
 *     Цей режим використовується для операцій типу "Read-Modify-Write" (читання-модифікація-запис),
 *     таких як exchange(), fetch_add(), compare_exchange_strong(). Оскільки така операція робить і читання,
 *     і запис одночасно, їй потрібні обидва правила:
 *       - Частина Acquire: гарантує, що наступні операції не перескочать вгору (ви бачите все, що було
 *         "випущено" іншим потоком через release).
 *       - Частина Release: гарантує, що попередні операції не впадуть вниз (ваші зміни стають видимими
 *         для інших потоків, які виконають acquire).
 *
 *
 *
 *
 *
 * -----------------------------------------------------------------------------------------------
 * Але навіщо нам взагалі потрібні ці прапорці
 *
 * Причина №1
 * Вся проблема в тому, що сучасні комп'ютери — це "брехуни" задля швидкості. Компілятор і процесор роблять
 * усе можливе, щоб програма працювала швидше, навіть якщо для цього треба поміняти інструкції місцями.
 *
 * Компілятор (GCC, Clang, MSVC) не знає, що ваш код працює у кілька потоків. Він аналізує функцію producer_func локально.
 *  void producer_func() {
 *      shared_data = 42; // (А) Звичайна змінна
 *      data_ready = true; // (Б) Атомарна змінна
 *  }
 *
 * Дивлячись на цей код, компілятор думає: «Хм, змінна shared_data і data_ready ніяк не пов'язані між собою.
 * Мені, як процесору, вигідніше спочатку виконати (Б), а потім (А), бо так дані краще ляжуть у кеш».
 *
 * Результат без acquire/release:
 *  1. Потік-виробник робить data_ready = true.
 *  2. Потік-споживач бачить data_ready == true, виходить із циклу while і читає shared_data.
 *  3. Але потік-виробник ще не встиг записати shared_data = 42! Споживач читає старе сміття або 0.
 *
 * Причина №2
 * Залізо: Кеші процесора та Out-of-Order execution
 * Навіть якщо компілятор згенерує правильний порядок, сучасні процесори (особливо ARM в айфонах/маках
 * або сучасні Intel/AMD) мають архітектуру Out-of-Order execution (виконання з closure поза порядком).
 * Вони мають так звані Store Buffers (буфери запису).
 *
 * Кожне ядро процесора має свій надшвидкий кеш (L1, L2). Коли Ядро 1 (Producer) пише shared_data = 42,
 * ця зміна не потрапляє в оперативну пам'ять миттєво. Вона "зависає" у локальному буфері Ядра 1.
 *
 * Якщо ми не використовуємо спеціальні бар'єри:
 *  1) Ядро 1 записує shared_data = 42 (осідає в буфері Ядра 1).
 *  2) Ядро 1 записує data_ready = true (і ця інформація чомусь швидше пробивається в загальний кеш L3,
 *     наприклад, бо лінія кешу була вільна).
 *  3) Ядро 2 (Consumer) бачить data_ready == true.
 *  4) Ядро 2 намагається прочитати shared_data, лізе у свій кеш або загальний L3, а там... досі 0,
 *     бо 42 все ще сидить у приватному буфері Ядра 1!
 *
 * memory_order_release змушує процесор "виштовхнути" (flush) всі попередні записи з буферів у загальну
 * видимість перед тим, як показати прапорець. А memory_order_acquire змушує Ядро 2 оновити свій
 * локальний кеш, щоб точно побачити те, що виштовхнуло Ядро 1.
 *
 *
 */

std::atomic<bool> data_ready {};
void base_example() {
    // ПОТІК 1: Producer
    int shared_data = 42; // 1. Звичайний запис
    // ------------------- БАР'ЄР RELEASE (ніщо не може впасти нижче) -------------------
    data_ready.store(true, std::memory_order_release); // 2. Атомарний сигнал


    // ПОТІК 2: Consumer
    while (!data_ready.load(std::memory_order_acquire)) {} // 3. Чекаємо на сигнал
    // ------------------- БАР'ЄР ACQUIRE (ніщо не може піднятися вище) -----------------
    // Як тільки load повернув true -> ми гарантовано бачимо shared_data = 42

    bool we_are_first = data_ready.exchange(false, std::memory_order_acq_rel);
    // Чому тут acq_rel?
    // 1. Нам потрібен Acquire, щоб безпечно читати дані далі (якщо ми перші).
    // 2. Нам потрібен Release, щоб скидання в false миттєво «опублікувалося» для потоку 3,
    //    і той дізнався, що він запізнився.
}


/**
 * Найкращий і найкласичніший приклад для std::memory_order_acq_rel — це реалізація Lock-free лічильника потоків
 * (або лічильника посилань, як у std::shared_ptr) або створення власного м'ютекса (Spinlock).
 *
 * Розберемо приклад зі Spinlock (спін-м'ютексом). Ми його вже реалізовували в першому розділі по std::atomic - std::atomic_flag
 *
 * Розберемо операцію lock_state.exchange(true, std::memory_order_acq_rel) через формулу «двостороннього агента»:
 * 1. Робота як Acquire (захист ЗНИЗУ)
 *    Коли потік успішно захопив м'ютекс (exchange повернув false), починає виконуватися код критичної секції: shared_counter++.
 *      - Що захищає Acquire: Він забороняє процесору та компілятору піднімати інструкцію shared_counter++ вище виклику lock().
 *
 *      - Наслідки порушення: Якби не було acquire, процесор міг би спекулятивно виконати shared_counter++ до того, як м'ютекс реально став наш.
 *        Це призвело б до повної руйнації даних, бо інший потік міг робити те саме в цей же момент.
 *
 * 2. Робота як Release (захист ЗВЕРХУ)
 *    Уяви, що Thread 1 заходить на друге коло циклу for. Він щойно зробив spin.unlock() (де був release), і відразу ж
 *    знову викликає spin.lock(), щоб знову збільшити лічильник.
 *      - Що захищає Release в acq_rel: Він гарантує, що попередні операції (попередній shared_counter++ та unlock) повністю
 *       завершилися в пам'яті і "не впадуть" нижче нового виклику lock().
 *
 *      - Він також миттєво публікує новий запис true (захоплення) для всіх інших ядер процесора.
 *
 */

class Spinlock {
private:
    // false = вільно, true = зайнято
    std::atomic<bool> lock_state{false};

public:
    void lock() {
        // exchange(true) записує true і ПОВЕРТАЄ старе значення.
        // Якщо старе значення було true, значить м'ютекс КИМОСЬ ЗАЙНЯТИЙ, і ми крутимося далі.
        // Якщо старе значення було false, то МИ ЙОГО ЗАЙНЯЛИ, і цикл завершується.
        while (lock_state.exchange(true, std::memory_order_acq_rel)) {
            // spin-wait (чекаємо)
        }
    }

    void unlock() {
        // Звільняємо м'ютекс. Тут достатньо просто release,
        // бо ми тільки записуємо false і "випускаємо" зміни потоку в світ.
        lock_state.store(false, std::memory_order_release);
    }
};

// Спільний ресурс, який ми будемо захищати
int shared_counter = 0;
Spinlock spin;

void increment_counter(int id) {
    for (int i = 0; i < 10000; ++i) {
        spin.lock();

        // КРИТИЧНА СЕКЦІЯ
        // Завдяки acq_rel, цей код залізобетонно захищений з обох сторін
        shared_counter++;

        spin.unlock();
    }
}

int main() {
    std::thread t1(increment_counter, 1);
    std::thread t2(increment_counter, 2);

    t1.join();
    t2.join();

    std::cout << "Final counter value: " << shared_counter << " (Expected: 20000)\n";
    return 0;
}