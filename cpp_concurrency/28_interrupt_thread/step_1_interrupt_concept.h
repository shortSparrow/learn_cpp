#include <iostream>
#include <thread>
#include <future>
#include <chrono>
#include <exception>

/**
 * =======================================================================================
 * ЧАСТИНА 1: Концепція переривання потоків та робота з thread_local
 * =======================================================================================
 *
 * У багатьох ситуаціях бажано подати сигнал довготривалому потоку, що настав час зупинитися.
 * Це може бути пов'язано з тим, що це робочий потік для пулу потоків, а пул зараз знищується,
 * або з тим, що робота, яку виконує потік, була явно скасована користувачем, або з безліччю
 * інших причин.
 *
 *
 * У C++ не можна просто так взяти й «убити» потік посеред роботи (на кшталт TerminateThread у Windows).
 * Примусове знищення призведе до витоку пам'яті, незакритих дескрипторів та заблокованих м'ютексів.
 * Зупинка має бути послідовною: головний потік виставляє прапорець (сигнал), а робочий потік
 * час від часу перевіряє цей прапорець і, якщо треба, безпечно завершує роботу.
 *
 * Архітектурна проблема доступу:
 * Для реалізації ми використовуємо прапорець зупинки:
 *      inline thread_local interruption_flag* this_thread_flag = nullptr;
 * У кожного окремого потоку є своя власна, незалежна копія цієї змінної.
 * Але як головний потік може до неї дотягнутися, щоб змінити її (виставити в true)? Головний потік
 * не має прямого доступу до змінних інших потоків.
 *
 * Рішення через вказівники та синхронізацію:
 * 1. Новий (робочий) потік запускається і першим ділом створює прапорець у своєму стеку.
 * 2. Цей же новий потік записує адресу створеного прапорця у свою власну `thread_local` змінну.
 *    Тепер будь-яка функція всередині цього потоку зможе перевірити статус через `this_thread_flag`.
 * 3. Оскільки головному потоку теж потрібно якось змінювати цей прапорець, новий потік бере
 *    адресу (вказівник) свого прапорця і «перекидає» її назад головному потоку через future,
 *    записуємо значення через p.set_value().
 * 4. Головний потік блокується в конструкторі (`fut.get()`) і чекає, поки новий потік створить
 *    прапорець і надішле його адресу.
 *
 * Головний потік зберігає цей отриманий вказівник у себе (в об'єкті `interruptible_thread`).
 * Коли ми викликаємо `t.interrupt()`, головний потік через цей вказівник напряму лізе в пам'ять
 * робочого потоку і змінює значення прапорця на true
 *
 *
 * Безпечне розкручування стеку:
 * Коли робочий потік викликає interruption_point(), він перевіряє свій прапорець. Якщо прапорець
 * виставлено, кидається спеціальне виключення `thread_interrupted`. Воно перехоплюється на самому
 * верху функції потоку. Це гарантує, що всі локальні об'єкти (деструктори) всередині робочої
 * функції відпрацюють коректно, і ми не отримаємо витоків ресурсів.
 *
 * Обмеження цього підходу:
 * Цей код ідеально працює, якщо потік виконує активні обчислення в циклі. Проте, якщо потік
 * заблокований на Condition Variable (сон в очікуванні події), він ніколи не дійде до чергової
 * перевірки interruption_point(). Тому що код просто засне на .wait() доки його не розбудять, і відповідно
 * він не побачить прапорець який надсилає головний потік.
 * Вирішення цієї проблеми розглядається в наступних частинах.
 */


/**
 * Спеціальне виключення для безпечного розкручування стеку потоку. Коли потік переривається, ми кидаємо це
 * виключення, щоб викликалися деструктори всіх локальних об'єктів усередині функції потоку.
 */
class thread_interrupted : public std::exception {
public:
    const char* what() const noexcept override {
        return "Thread was interrupted cooperatively.";
    }
};

// Клас, який представляє прапорець переривання.
class interruption_flag {
private:
    std::atomic<bool> flag{false};
public:
    void set() {
        flag.store(true, std::memory_order_relaxed);
    }
    bool is_set() const {
        return flag.load(std::memory_order_relaxed);
    }
};

/**
 * Цей рядок створює глобальну (або точніше — статичну в межах простору імен) змінну.
 * Але ключове слово тут — thread_local. Воно каже компілятору: «Ця змінна не одна на всю програму.
 * Для кожного потоку, який буде створено в системі, виділи окрему, персональну копію цієї змінної».
 */
inline thread_local interruption_flag* this_thread_flag = nullptr;

// Точка переривання. Її потрібно розставляти в місцях тривалих обчислень або перед важкими операціями.
void interruption_point() {
    if (this_thread_flag && this_thread_flag->is_set()) {
        throw thread_interrupted();
    }
}

// Кастомний клас для керування потоком
class interruptible_thread {
private:
    std::thread internal_thread;
    interruption_flag* flag = nullptr; // Вказівник на прапорець, який живе всередині потоку
public:
    template<typename Function>
    interruptible_thread(Function f) {
        // Використовуємо promise, щоб гарантовано передати адресу прапорця
        // з новоствореного потоку назад у батьківський потік.
        std::promise<interruption_flag*> p;
        std::future<interruption_flag*> fut = p.get_future();

        internal_thread = std::thread([f, p = std::move(p)]() mutable {
            // 1. Створюємо прапорець у стеку нового потоку
            interruption_flag local_flag;

            /**
             * 2. Встановлюємо thread_local змінну для цього потоку
             * Може здатися питання, нафіга нам ще одна змінна яка зберігає посилання на local_flag.
             * Відповідь в тому, що ми в потоці маємо десь поставити перевірку чи не викликано переривання, тобто
             * функцію interruption_point, у нас вона викликається у long_running_task, тут у нас це функція f()
             * передана як аргумент, от якби ми не мали глобальної змінної то важко було б передати посилання,
             * довелося б перекидати його як аргумент у багато функції.
             */
            this_thread_flag = &local_flag;

            // 3. Відправляємо адресу прапорця у батьківський потік
            p.set_value(&local_flag);

            try {
                // 4. Запускаємо корисну роботу користувача
                f();
            } catch (const thread_interrupted& e) {
                // Виключення перехоплюється на самому верху потоку.
                // Стек успішно розкручено, деструктори локальних об'єктів f() відпрацювали.
                std::cout << "[Thread] Caught interruption exception: " << e.what() << "\n";
            } catch (...) {
                std::cout << "[Thread] Caught unknown exception.\n";
            }

            // 5. Очищаємо thread_local вказівник перед виходом
            this_thread_flag = nullptr;
        });

        // Блокуємо конструктор батьківського потоку, поки новий потік не створить
        // свій прапорець і не передасть його адресу. Це запобігає Race Condition,
        // коли ми намагаємося викликати interrupt() до того, як потік взагалі стартував.
        flag = fut.get();
    }

    // Метод для надсилання сигналу переривання
    void interrupt() {
        if (flag) {
            flag->set();
        }
    }

    void join() {
        if (internal_thread.joinable()) {
            internal_thread.join();
        }
    }

    ~interruptible_thread() {
        join();
    }
};

// --- Демонстрація роботи ---

void long_running_task() {
    std::cout << "[Task] Started working...\n";
    for (int i = 0; i < 100; ++i) {
        // Імітація обчислень
        std::this_thread::sleep_for(std::chrono::milliseconds(50));

        // Регулярно перевіряємо, чи не попросили нас зупинитися
        interruption_point();

        if (i % 5 == 0) {
            std::cout << "[Task] Working on step " << i << "...\n";
        }
    }
    std::cout << "[Task] Finished successfully (should not happen if interrupted).\n";
}

int main_1() {
    std::cout << "[Main] Creating interruptible thread...\n";
    interruptible_thread t(long_running_task);

    // Даємо потоку трохи попрацювати
    std::this_thread::sleep_for(std::chrono::milliseconds(300));

    std::cout << "[Main] Signaling interrupt...\n";
    t.interrupt(); // Надсилаємо сигнал зупинки

    t.join();
    std::cout << "[Main] Thread joined. Exiting.\n";
    return 0;
}
