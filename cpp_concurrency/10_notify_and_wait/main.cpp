#include <iostream>
#include <thread>
#include <mutex>
#include <condition_variable>
#include <queue>
#include <chrono>

/**
 * Уявімо ситуацію: Потік А готує дані, а Потік Б має їх обробити. Як Потоку Б дізнатися, що дані готові?
 *
 * Ось три підходи, від найгіршого до найкращого:
 *  1. Постійна перевірка (Busy-wait)
 *   Це як їхати в поїзді і кожну хвилину питати машиніста: «Ми вже приїхали?».
 *   Проблема: Процесор завантажений на 100%, бо потік постійно ганяє цикл перевірки ( while(is_ready){...} ).
 *   Блокування: Якщо потік тримає м'ютекс (lock) під час перевірки, інший потік не зможе навіть покласти дані в чергу, бо «двері зачинені».
 *
 *  2. Перевірка з паузою (Sleep)
 *   Ви ставите будильник на кожні 10 хвилин, прокидаєтесь і дивитесь чи приїхали.
 *    Плюс: Процесор відпочиває.
 *    Проблема: Важко вгадати час. Якщо поставити 100 мс, а дані прийшли через 1 мс — ви дарма спите 99 мс. Це критично для ігор або систем реального часу.
 *
 *  3. Умовні змінні (std::condition_variable) — Ідеальний варіант
 *    Це як попросити провідника: «Розбудіть мене, коли буде моя станція». Ви спите і не витрачаєте енергію, а прокидаєтесь рівно тоді, коли треба.
 *
 * У код нижче реалізовано третій варіант
 * У нас є два потоки (t1 та t2), t1 підготовлює дані, і ми вважаємо що це довга операція, а t2 має опрацювати вже
 * підготовлені дані (це швидка операція). Отже, t1 починає підготовлювати дані (це коли потік засинає на 500 мс),
 * коли дані отримані ми виводимо їх у термінал ([Producer] Prepare data:...) і блокуємо м'ютекс перед .push, щоб
 * не було конфліктів з потенційними іншими потоками які теж підготовлюють дані (Тому, що хоч для нас .push це і одна операція, але для процесора це кілька операцій:
 *  1. Виділяє пам'ять для нового вузла.
 *  2. Копіює дані у цей вузол.
 *  3. Оновлює вказівник на "хвіст" черги.
 *  4. Оновлює лічильник розміру черги (size).
 * ). Саме тому якщо є два потоки які одночасно роблять .push() то можуть бути конфлікти і race condition.
 * Після цього ми сповіщаємо через .notify_one() всіх, хто чекає на закінчення роботи. В нашому випадку це потік t2. Сам потік t2 запустився ще раніше,
 * але дійшовши до .wait() він заснув, бо lambda повернула false, бо finished=false і data_queue порожнє. Але зараз .wait() прокидається знову і
 * робить перевірку (finished=false, але data_queue вже не порожнє), оскільки lambda повертає true, ми ідемо далі, дістаємо перший елемент
 * з queue і розблоковуємо м'ютекс, щоб дати можливість відпрацювати потік t1 якщо він встигне, а якщо ні, не страшно, бо ми підемо на початок
 * while, заблокуємо м'ютекс, потім підемо у .wait() і якщо черга все ще порожня (ми видалили попереднє значення звідти, тож якщо t1 не встиг покласти
 * туди нове значення то черга порожня), то .wait() відпускає м'ютекс і засинає. В цей момент потік t1 вже опрацював дані, бо імітацію
 * важкої роботи м'ютекс не блокує, і він готовий робити новий .push(). Блокує м'ютекс (для уникнення race condition) і через .notify_one()
 * сповіщає t2 що той може опрацювати наступні дані.
 * І так відбувається доки t1 не закінчить всю свою роботу і не поставить finished у true і викличе .notify_one() щоб сповістити про це t2.
 *
 */


// Структура для імітації даних
struct data_chunk {
    int value;
};

// Глобальні змінні для синхронізації
std::mutex mut;
std::queue<data_chunk> data_queue;
std::condition_variable data_cond;

bool finished = false; // Прапорець завершення роботи

// Функція, яка готує дані (Producer)
void data_preparation_thread() {
    for (int i = 1; i <= 5; ++i) {
        std::this_thread::sleep_for(std::chrono::milliseconds(500)); // Імітація важкої роботи

        data_chunk data = { i * 10 };

        std::cout << "[Producer] Prepare data: " << data.value << std::endl;

        {
            std::lock_guard<std::mutex> lk(mut);
            data_queue.push(data);
        } // М'ютекс автоматично звільняється тут (кінець області видимості)

        data_cond.notify_one(); // Сповіщаємо потік, що чекає
    }

    // Сигнал про те, що даних більше не буде
    {
        std::lock_guard<std::mutex> lk(mut);
        finished = true;
    }
    data_cond.notify_one();
}

// Функція, яка обробляє дані (Consumer)
void data_processing_thread() {
    while (true) {
        std::unique_lock<std::mutex> lk(mut); // .lock() викликається одразу, тому наш м'ютекс заблокований (lock)

        // wait() робить три речі:
        // 1. Перевіряє умову (лямбда-функцію).
        // 2. Якщо false — відпускає м'ютекс (.unlock()) і засинає.
        // 3. Коли приходить notify_one, прокидається, блокує м'ютекс і перевіряє ще раз, і так по колу, доки не буде true.
        data_cond.wait(lk, [] {
            return !data_queue.empty() || finished; // Якщо повертає false, то wait() розблоковує м'ютекс і переводить потік у стан блокування або очікування
        });

        if (data_queue.empty() && finished) {
            break; // Вихід, якщо даних немає і робота завершена
        }

        data_chunk data = data_queue.front();
        data_queue.pop();

        // Розблоковуємо м'ютекс перед обробкою, щоб не тримати його занадто довго
        lk.unlock();

        std::cout << "[Consumer] Data processed: " << data.value << std::endl;
    }
}



int main() {
    std::thread t1(data_preparation_thread);
    std::thread t2(data_processing_thread);

    t1.join();
    t2.join();

    std::cout << "Process done." << std::endl;

    /**
     * [Producer] Prepare data: 10
     * [Consumer] Data processed: 10
     * [Producer] Prepare data: 20
     * [Consumer] Data processed: 20
     * [Producer] Prepare data: 30
     * [Consumer] Data processed: 30
     * [Producer] Prepare data: 40
     * [Consumer] Data processed: 40
     * [Producer] Prepare data: 50
     * [Consumer] Data processed: 50
     * Process done.
     */

    return 0;
}


