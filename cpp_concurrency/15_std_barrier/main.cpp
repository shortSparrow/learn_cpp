#include <iostream>
#include <thread>
#include <vector>
#include <barrier>
#include <string>
#include <locale>

/**
 * std::barrier — це багаторазовий (reusable) засіб синхронізації, представлений у C++20 у заголовному файлі <barrier>.
 * Він корисний у сценаріях, де група потоків виконує циклічний (ітеративний) алгоритм крок за кроком (по фазах).
 *
 * Основна відмінність від std::latch полягає в тому, що після того, як усі потоки досягли бар'єра, він не залишається
 * «відкритим» назавжди, а автоматично скидає свій лічильник до початкового значення і переходить до наступної фази.
 *
 * Основні методи:
 *  Конструктор: explicit barrier(std::ptrdiff_t expected, CompletionFunction f = CompletionFunction());
 *              Ініціалізує лічильник значень expected. Також приймає об'єкт функції, яка буде виконана після того,
 *              як усі потоки досягнуть бар'єра, але до того, як вони будуть розблоковані.
 *
 *  arrive_and_wait(): Основний робочий метод. Потік зменшує лічильник бар'єра на 1 і блокується (очікує),
 *                      поки поточна фаза не завершиться (тобто поки лічильник не стане рівним нулю завдяки іншим потокам).
 *                      Коли лічильник досягає нуля, один із потоків виконує CompletionFunction, після чого лічильник
 *                      відновлюється до expected, фаза змінюється, і всі потоки розблоковуються.
 *
 *  arrive_and_drop(): Зменшує лічильник поточного кроку на 1, а також назавжди зменшує значення expected на 1 для всіх
 *                     наступних фаз. Потік, який викликав цей метод, не блокується, а продовжує виконання.
 *                     Це використовується, якщо потік завершив свою участь у загальному циклі обчислень і більше не
 *                     повернеться на наступних ітераціях.
 *
 *
 * Типовий приклад — паралельна обробка матриць (наприклад, у графіці або фізичних симуляціях),
 * де на кроці 1 кожен потік обчислює свій шматок даних, а на кроці 2 кожен потік має зчитати
 * результати сусідніх потоків. Потік не може почати крок 2, поки абсолютно всі потоки не завершать крок 1.
 * std::barrier ідеально підходить для таких ітеративних синхронізацій, позбавляючи потреби
 * створювати нові std::latch на кожну ітерацію циклу
 *
 * Однією з найпотужніших фіч std::barrier є можливість задати Completion Function. Це функція (або лямбда, або функтор),
 * яка викликається автоматично, коли лічильник поточної фази зменшується до нуля.
 * Функція завершення виконується тільки одним із потоків, які досягли бар'єра. Усі інші потоки в цей час заблоковані й чекають.
 * Якщо функція завершення викидає виняток, програма викликає std::terminate(). Вона має бути noexcept.
 */


int main() {
    std::setlocale(LC_ALL, "uk_UA.UTF-8");

    const int num_threads = 3;
    const int num_rounds = 2;
    std::vector<int> shared_data = {1, 2, 3};

    // Лямбда-функція, яка буде викликатися автоматично
    // ОДНИМ із потоків наприкінці кожної фази (раунду).
    auto on_completion = [&]() noexcept {
        static int round_counter = 1;
        std::cout << "\n--- Завершено раунд " << round_counter++ << " ---" << std::endl;
        std::cout << "Поточний стан даних: ";
        for (int val : shared_data) {
            std::cout << val << " ";
        }
        std::cout << "\n----------------------------\n" << std::endl;
    };

    // Ініціалізуємо бар'єр на 3 потоки із нашою функцією завершення
    std::barrier barrier_obj(num_threads, on_completion);

    auto worker = [&](int id) {
        for (int round = 0; round < num_rounds; ++round) {
            // Крок 1: Паралельні обчислення (кожен потік працює зі своїми даними)
            shared_data[id] *= 2;

            // Безпечний вивід у консоль
            std::string msg = "Потік " + std::to_string(id) + " завершив роботу в раунді " + std::to_string(round + 1) + "\n";
            std::cout << msg;

            // Крок 2: Точка синхронізації.
            // Потік зменшує лічильник бар'єра і блокується.
            // Коли зайде останній потік, виконається on_completion,
            // бар'єр скинеться, і всі потоки розблокуються для наступного раунду.
            barrier_obj.arrive_and_wait();

            // Наступний раунд почнеться ТІЛЬКИ після того, як всі потоки пройдуть бар'єр
        }
    };

    // Запуск потоків
    std::vector<std::thread> threads;
    for (int i = 0; i < num_threads; ++i) {
        threads.emplace_back(worker, i);
    }

    // Очікування завершення потоків
    for (auto& t : threads) {
        t.join();
    }


    /**
     * Ось що виведе термінал:
     *
     * Потік 0 завершив роботу в раунді 1
     * Потік 2 завершив роботу в раунді 1
     * Потік 1 завершив роботу в раунді 1
     *
     * --- Завершено раунд 1 ---
     * Поточний стан даних: 2 4 6
     * ----------------------------
     *
     * Потік 0 завершив роботу в раунді 2
     * Потік 2 завершив роботу в раунді 2
     * Потік 1 завершив роботу в раунді 2
     *
     * --- Завершено раунд 2 ---
     * Поточний стан даних: 4 8 12
     * ----------------------------
     *
     */

    return 0;
}