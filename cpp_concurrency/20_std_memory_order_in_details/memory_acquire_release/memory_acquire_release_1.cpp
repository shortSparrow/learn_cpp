#include "../include/memory_acquire_release/memory_acquire_release_1.h"

#include <atomic>
#include <string>
#include <thread>
#include <cassert>
#include <assert.h>

/**
 *
 * Модель впорядкування пам'яті Acquire-Release (Придбання-Випуск) — це, мабуть, найважливіша концепція в асинхронному
 * програмуванні на C++. Вона є тією самою "золотою серединою": працює значно швидше за суворий seq_cst, але дає
 * залізобетонні гарантії синхронізації, яких взагалі немає у relaxed.
 *
 * Головна ідея цієї моделі полягає в тому, що синхронізація відбувається попарно між конкретними
 * потоками (pairwise synchronization) і тільки навколо конкретної атомарної змінної. Тут немає єдиного для всієї
 * системи глобального порядку, але є чіткий зв'язок між потоком, який записує дані, і потоком, який їх читає.
 *
 * Для цього використовуються три режими:
 *      1) std::memory_order_release (Випуск) — використовується для операцій запису (store).
 *      2) std::memory_order_acquire (Придбання) — використовується для операцій читання (load).
 *      3) std::memory_order_acq_rel — комбінація для операцій типу "прочитати-змінити-записати"
 *         (наприклад, fetch_add або compare_exchange_strong).
 *
 *
 *
 * Як це працює? (Відносини Synchronizes-with)
 * Коли Потік А виконує запис у змінну з режимом release, а Потік Б виконує читання тієї самої змінної з режимом acquire
 * і бачить записане Потоком А значення, між ними встановлюється зв'язок "синхронізовано з" (synchronizes-with).
 *
 * Це створює дві найважливіші гарантії для компілятора та процесора:
 *  - Заборона перестановки інструкцій "вниз" для Release: Жоден запис чи читання (атомарні або звичайні), які в коді
 *    стоять перед store(..., memory_order_release), не можуть бути переставлені компілятором або процесором нижче цього атомарного запису.
 *  - Заборона перестановки інструкцій "вгору" для Acquire: Жоден запис чи читання, які в коді стоять після load(memory_order_acquire),
 *    не можуть бути переставлені вище.
 *
 *
 * В прикладі нижче data == "Важливі дані" завжди буде true, тому що є порядок між записом і читанням.
 * В середині producer першим завжди буде записування значення у data, а другим записування true в ready,
 * і consumer теж має порядок, спочатку він читає дані через !ready.load(), а тільки потім йде до порівняння assert().
 */

// Приклад 1. Базовий приклад для кращого розуміння
std::string data; // Звичайна, НЕ атомарна змінна!
std::atomic<bool> ready{false};

void producer() {
    data = "Важливі дані"; // 1. Запис у звичайну змінну
    ready.store(true, std::memory_order_release); // 2. Атомарний випуск
}

void consumer() {
    // 3. Чекаємо, поки ready стане true за допомогою acquire
    while (!ready.load(std::memory_order_acquire));

    // 4. Читаємо звичайну змінну
    assert(data == "Важливі дані"); // Гарантовано успішно!
}


