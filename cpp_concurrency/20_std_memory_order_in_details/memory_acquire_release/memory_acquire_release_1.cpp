/**
 * На перший погляд може здатися, що z не може бути 0, але це не так!
 *
 * Можна подумати, що якщо x став true для першого потоку (read_x_then_y), то він автоматично і миттєво став true і
 * для другого потоку (read_y_then_x). Але в моделі Acquire-Release це не так.
 *
 * Синхронізація Acquire-Release працює тільки попарно між тим, хто пише в конкретну змінну, і тим, хто з неї читає.
 *      1) write_x синхронізується з read_x_then_y (через змінну x).
 *      2) write_y синхронізується з read_y_then_x (через змінну y).
 * Але між потоками write_x та write_y немає жодного зв'язку. Вони виконуються повністю незалежно.
 *
 *
 * Сценарій, за якого z == 0
 * Уявимо архітектуру процесора: Потік a (write_x) працює на Ядрі 1, Потік b (write_y) — на Ядрі 2,
 * а читачі — на Ядрах 3 і 4 відповідно.
 *  1) Ядро 1 виконує x.store(true). Ця зміна потрапляє в його локальний буфер і починає повільно поширюватися
 *     по шині пам'яті до інших ядер.
 *  2) Ядро 2 виконує y.store(true). Ця зміна так само починає поширюватися.
 *  3) До Ядра 3 (read_x_then_y) звістка про те, що x == true, дійшла швидко. Потік виходить із циклу while.
 *     Але звістка про те, що y == true (від Ядра 2), сюди ще не долетіла. Тому Ядро 3 читає зі свого кешу
 *     старе значення y == false. Умова if(y) не спрацьовує, z не збільшується.
 *  4) Одночасно з цим на Ядрі 4 (read_y_then_x) ситуація дзеркальна: туди швидко дійшла інформація про те, що y == true.
 *     Потік виходить зі свого циклу while. Але інформація про x == true (від Ядра 1) сюди ще не долетіла! Ядро 4 бачить
 *     у своєму кеші x == false. Умова if(x) не спрацьовує, z знову не збільшується.
 *
 * Оскільки std::memory_order_acquire та std::memory_order_release не вимагають від процесора будувати єдину чергу подій
 * для всіх змінних (як це робить seq_cst), процесор дозволяє різним ядрам бачити ці дві події у різному порядку.
 *
 *
 * Нагадування
 * Важливо розуміти, що у межах одного потоку, компілятор (не залежно від memory_order) зобов'язаний
 * зберегти логіку програми. Тобто у функції order_acquire_release
 *      x=false;
 *      y=false;
 *      z=0;
 *      std::thread a(write_x);
 *      std::thread b(write_y);
 *      std::thread c(read_x_then_y);
 *      std::thread d(read_y_then_x);
 *
 * У нас x=false та y=false можуть помінятися місцями, а от x=false та td::thread a(write_x) вже ні.
 *
 */
namespace order_acquire_release {
    std::atomic<bool> x,y;
    std::atomic<int> z;
    void write_x() {
        x.store(true,std::memory_order_release);
    }

    void write_y() {
        y.store(true,std::memory_order_release);
    }

    void read_x_then_y() {
        while(!x.load(std::memory_order_acquire));
        if(y.load(std::memory_order_acquire))
            ++z;
    }

    void read_y_then_x() {
        while(!y.load(std::memory_order_acquire));
        if(x.load(std::memory_order_acquire))
            ++z;
    }

    void run_code() {
        x=false;
        y=false;
        z=0;
        std::thread a(write_x);
        std::thread b(write_y);
        std::thread c(read_x_then_y);
        std::thread d(read_y_then_x);
        a.join();
        b.join();
        c.join();
        d.join();
        assert(z.load()!=0);
    }
}


