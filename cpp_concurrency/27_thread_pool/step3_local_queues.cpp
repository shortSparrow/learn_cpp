/**
 * Крок 3: Пул потоків із локальними чергами
 *
 * У чому проблема єдиної спільної черги?
 * 1. Постійне блокування: У момент завершення завдання всі вільні потоки одночасно
 *    біжать до єдиного м'ютекса спільної черги.
 * 2. Ефект "Cache Ping-Pong": Кожного разу, коли потік модифікує спільну чергу,
 *    кеш-рядок процесора, що містить покажчики черги, має бути інвалідований на всіх інших ядрах.
 *    Це змушує ядра постійно пересилати дані кешу між собою, що знижує продуктивність системи.
 * 3. Потік-відправник (Submitter): Зовнішній потік, який постійно «нарізає» та закидає нові
 *    завдання через submit(), постійно конкурує з робочими потоками пулу.
 *
 * Як локальна черга змінює правила гри:
 * 1. Локальне додавання (Push): Коли робочий потік виконує завдання і воно породжує підзавдання
 *    (наприклад, у QuickSort), він додає їх у свою власну локальну чергу.
 *    Для цього взагалі не потрібен глобальний м'ютекс.
 * 2. Локальне отримання (Pop): Потік перш за все дивиться у свою локальну чергу.
 *    Оскільки він працює з нею локально, конкуренція за дані з іншими потоками дорівнює нулю.
 * 3. Краща локальність кешу: Дані завдання, які потік щойно створив, найімовірніше, вже знаходяться
 *    у швидкому кеші цього ж ядра. Виконуючи їх локально, ми уникаємо перенесення даних між ядрами.
 *
 *
 * Тобто навантаження на загальну чергу має зменшитися, бо дочірні задачі будуть лишаться у локальних чергах, а не йти у
 * глобальну. Це добре працює для зменшення конфліктів (що всі лізуть в глобальну чергу і блокують одне одного),
 * але коли розподіл роботи нерівномірним, це може легко призвести до того, що один потік матиме багато роботи в своїй
 * черзі, а інші не матимуть що робити.
 */


class thread_pool {
    std::atomic_bool done;
    threadsafe_queue<function_wrapper> pool_work_queue; // Загальна глобальна черга
    using local_queue_type = std::queue<function_wrapper>;
    static inline thread_local std::unique_ptr<local_queue_type> local_work_queue = nullptr;

    std::vector<std::thread> threads;
    join_threads joiner;

    void worker_thread() {
        // Кожен робочий потік створює свою особисту чергу в купі
        local_work_queue.reset(new local_queue_type);

        while (!done) {
            run_pending_task();
        }
    }

public:
    thread_pool() : done(false), joiner(threads) {
        unsigned const thread_count = std::thread::hardware_concurrency();
        try {
            for (unsigned i = 0; i < thread_count; ++i) {
                threads.emplace_back(&thread_pool::worker_thread, this);
            }
        } catch (...) {
            done = true;
            throw;
        }
    }

    ~thread_pool() {
        done = true;
    }

    /**
     * Тут стоїть умова на те, хто саме викликає submit.
     * 1. Якщо виклик йде ззовні (наприклад, з main), то змінна local_work_queue
     *    рівна nullptr, відповідно завдання кладеться у загальну чергу pool_work_queue.
     * 2. Якщо потік всередині пулу виконує задачу і викликає submit() для підзадач,
     *    то для нього local_work_queue вже ініціалізований. Задача миттєво і без
     *    жодних блокувань глобального м'ютекса летить у його особисту локальну чергу!
     */
    template<typename FunctionType>
    std::future<std::invoke_result_t<FunctionType>> submit(FunctionType f) {
        using result_type = std::invoke_result_t<FunctionType>;

        std::packaged_task<result_type()> task(f);
        std::future<result_type> res(task.get_future());

        if (local_work_queue) {
            local_work_queue->push(function_wrapper(std::move(task)));
        } else {
            pool_work_queue.push(function_wrapper(std::move(task)));
        }
        return res;
    }

    /**
     * Порядок перевірки завдань залізобетонний:
     * 1. Спочатку потік перевіряє свою локальну чергу (0% конкуренції з іншими потоками).
     * 2. Якщо своя порожня, лізе в загальну чергу.
     * 3. Якщо і там пусто — робить паузу через yield().
     */
    void run_pending_task() {
        function_wrapper task;
        if (local_work_queue && !local_work_queue->empty()) {
            task = std::move(local_work_queue->front());
            local_work_queue->pop();
            task();
        } else if (pool_work_queue.try_pop(task)) {
            task();
        } else {
            std::this_thread::yield();
        }
    }
};

/**
 * Великий недолік цього підходу (Ось чому потрібен Крок 4):
 *
 * Навантаження на загальну чергу зменшилося, але коли розподіл роботи є нерівномірним,
 * це легко призводить до ситуації, коли один потік завалений роботою, а інші простоюють.
 *
 * Припустимо, ми працюємо з алгоритмом QuickSort на 4 потоках:
 * 1. Перша задача приходить у глобальну чергу. Її бере Потік №0.
 * 2. Потік №0 знаходить pivot і ділить масив на 2 шматки.
 * 3. Один шматок він кидає у свою локальну чергу (local_work_queue), а другий починає обробляти сам.
 * 4. На наступній ітерації він знову розділить свій поточний шматок на два і знову покладе один у свою чергу.
 *
 * Проблема: Оскільки локальна черга Потоку №0 є звичайною `std::queue` й інкапсульована всередині нього,
 * Потоки №1, №2 та №3 ніяк не можуть отримати до неї доступ. Вони дивляться в порожню глобальну чергу,
 * нічого там не знаходять і марно крутять цикл з yield().
 * Виходить, що реально працює лише один потік, а 3 інші просто голодують і нічого не роблять.
 *
 * Щоб вирішити цю проблему, нам потрібно дозволити вільним потокам «красти» роботу у своїх колег.
 */